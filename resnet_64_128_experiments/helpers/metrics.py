def plot_per_class_accuracy(train_history, class_names=None):
    # last epoch’s per-class accuracy
    per_class_acc = train_history["val_per_class_acc"][-1]  # np.array [num_classes]

    num_classes = len(per_class_acc)
    indices = np.arange(num_classes)

    plt.figure(figsize=(8, 4))
    plt.bar(indices, per_class_acc)

    if class_names is None:
        class_names = [str(i) for i in range(num_classes)]

    plt.xticks(indices, class_names, rotation=45, ha='right')
    plt.ylabel("Accuracy (Recall)")
    plt.title("Per-Class Validation Accuracy (Last Epoch)")
    plt.ylim(0, 1.0)
    plt.tight_layout()

    return plt


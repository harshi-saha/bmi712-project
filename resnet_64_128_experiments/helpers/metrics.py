def compute_auc_multiclass(model, loader, device=device, average: Literal['macro', 'weighted'] | None="macro"):
    """
    Computes multi-class ROC AUC using one-vs-rest scheme.

    :param model: The model to use to compute AUC
    :param loader: The DataLoader for the dataset to compute AUC using.
    :param device: The device to run the AUC computation on.
    :param average: "macro", "weighted", or None (see sklearn.roc_auc_score docs)
    """
    model.eval()
    y_true = []
    y_score = []

    with torch.no_grad():
        for images, labels in loader:
            images = images.to(device)
            labels = labels.squeeze().long().to(device)

            outputs = model(images)                  # (B, C)
            probs = torch.softmax(outputs, dim=1)    # class probabilities

            y_true.append(labels.cpu())
            y_score.append(probs.cpu())

    y_true = torch.cat(y_true).numpy()      # shape: (N,)
    y_score = torch.cat(y_score).numpy()    # shape: (N, C)

    # multi_class="ovr" is typical, "ovo" also available
    auc = roc_auc_score(
        y_true, 
        y_score, 
        multi_class="ovr", 
        average=average
    )
    return auc

def plot_train_hist(train_history, type: Literal["loss", "acc"]):
    train_col = f"train_{type}"
    val_col = f"val_{type}"

    epochs = range(1, len(train_history[train_col]) + 1)
    plt.figure()

    plt.plot(epochs, train_history[train_col], label="Train")
    plt.plot(epochs, train_history[val_col], label="Validation")

    plt.xlabel("Epoch")
    plt.ylabel(type.upper())
    plt.legend()
    plt.title(f"Training vs. Validation {type.upper()}")

    return plt


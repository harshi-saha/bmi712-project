def compute_auc_dermamnist(
        model, 
        loader, 
        split: Literal['train', 'val', 'test'], 
        size: Literal[64, 128], 
        device=device
    ):
    """
    Compute AUC on the DermaMNIST dataset.

    This function uses a helper in the MedMNIST package to compute AUC, so it is specific to DermaMNIST.
    For other datasets, please use `compute_auc_multiclass` instead.

    :param model: The model for which to compute AUC.
    :param loader: A DataLoader for the dataset to compute AUC using. Must be a DermaMNIST dataset.
    :param split: The split of the DermaMNIST dataset you are computing AUC on.
    :param size: The size of the images.
    :param device: The device to use for running the model to compute AUC.
    """
    model.eval()
    
    y_true = []
    y_score = []

    with torch.no_grad():
        for images, labels in loader:
            images = images.to(device)
            labels = labels.squeeze().long().to(device)

            outputs = model(images)
            probs = torch.softmax(outputs, dim=1)

            y_true.append(labels.cpu())
            y_score.append(probs.cpu())

    y_true = torch.cat(y_true).numpy()
    y_score = torch.cat(y_score).numpy()

    evaluator = Evaluator("dermamnist", split, size=size)
    metrics = evaluator.evaluate(y_score)

    return metrics

